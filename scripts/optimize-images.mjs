// Converts the client's source images (assets/source) into responsive AVIF/WebP
// files in public/images and writes their dimensions to src/lib/images.generated.ts.
// Usage: npm run images
import { mkdir, writeFile, copyFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const src = (f) => path.join(root, "assets/source", f);
const outDir = path.join(root, "public/images");

// widths are output pixel widths; never upscale past the source width.
const images = {
  "logo-lion-L": { file: "logo-lion-L.png", widths: [64, 96, 128, 192, 256, 400] },
  "ceo-portrait-gold": { file: "ceo-portrait-gold.png", widths: [320, 480, 600] },
  "ceo-portrait-cutout": { file: "ceo-portrait-cutout.png", widths: [320, 500] },
  "ceo-speaking": { file: "ceo-speaking.png", widths: [320, 499] },
  "ceo-portrait-smile": { file: "ceo-portrait-smile.png", widths: [320, 480, 600] },
  "ceo-presenting": { file: "ceo-presenting.png", widths: [320, 504] },
  "team-working-session": { file: "team-working-session.jpg", widths: [480, 720, 903] },
};

await mkdir(outDir, { recursive: true });
const manifest = {};

for (const [name, { file, widths }] of Object.entries(images)) {
  const input = sharp(src(file));
  const { width, height } = await input.metadata();
  const usable = widths.filter((w) => w <= width);
  for (const w of usable) {
    const resized = sharp(src(file)).resize({ width: w });
    await resized.clone().avif({ quality: 60, effort: 6 }).toFile(path.join(outDir, `${name}-${w}.avif`));
    await resized.clone().webp({ quality: 78, effort: 6 }).toFile(path.join(outDir, `${name}-${w}.webp`));
  }
  manifest[name] = { width, height, widths: usable };
  console.log(`${name}: ${width}x${height} -> ${usable.join(", ")}`);
}

// Depth map for the liquid-metal logo (MetallicPaint). Same algorithm as the
// React Bits component, run once here instead of on every visitor's device:
// a relaxed Poisson solve inside the logo shape, stored as gray = depth, alpha = shape.
{
  const size = 600;
  const { data, info } = await sharp(src("logo-lion-L.png"))
    .resize({ width: size })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const { width, height } = info;
  const n = width * height;
  const alpha = new Float32Array(n);
  const shape = new Uint8Array(n);
  const boundary = new Uint8Array(n);
  for (let i = 0; i < n; i++) {
    const [r, g, b, a] = [data[i * 4], data[i * 4 + 1], data[i * 4 + 2], data[i * 4 + 3]];
    const background = (r > 250 && g > 250 && b > 250 && a === 255) || a < 5;
    alpha[i] = background ? 0 : a / 255;
    shape[i] = alpha[i] > 0.1 ? 1 : 0;
  }
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const i = y * width + x;
      if (!shape[i]) continue;
      if (x === 0 || x === width - 1 || y === 0 || y === height - 1 || !shape[i - 1] || !shape[i + 1] || !shape[i - width] || !shape[i + width]) {
        boundary[i] = 1;
      }
    }
  }
  const u = new Float32Array(n);
  for (let iter = 0; iter < 200; iter++) {
    for (let y = 1; y < height - 1; y++) {
      for (let x = 1; x < width - 1; x++) {
        const i = y * width + x;
        if (!shape[i] || boundary[i]) continue;
        const sum = (shape[i + 1] ? u[i + 1] : 0) + (shape[i - 1] ? u[i - 1] : 0) + (shape[i + width] ? u[i + width] : 0) + (shape[i - width] ? u[i - width] : 0);
        u[i] = 1.85 * ((0.01 + sum) / 4) + (1 - 1.85) * u[i];
      }
    }
  }
  let max = 0;
  for (let i = 0; i < n; i++) max = Math.max(max, u[i]);
  const out = Buffer.alloc(n * 4);
  for (let i = 0; i < n; i++) {
    const depth = u[i] / (max || 1);
    const gray = Math.round(255 * (1 - depth * depth));
    out[i * 4] = out[i * 4 + 1] = out[i * 4 + 2] = gray;
    out[i * 4 + 3] = Math.round(alpha[i] * 255);
  }
  await sharp(out, { raw: { width, height, channels: 4 } }).png({ compressionLevel: 9 }).toFile(path.join(outDir, "logo-lion-L-depth.png"));
  console.log(`logo-lion-L-depth.png: ${width}x${height}`);
}

// Favicons: reuse the live site's existing crops unchanged.
await copyFile(src("favicon-192.png"), path.join(root, "src/app/icon.png"));
await copyFile(src("favicon-180.png"), path.join(root, "src/app/apple-icon.png"));

const ts = `// Generated by scripts/optimize-images.mjs. Do not edit by hand.
export const imageManifest = ${JSON.stringify(manifest, null, 2)} as const;

export type ImageName = keyof typeof imageManifest;
`;
await writeFile(path.join(root, "src/lib/images.generated.ts"), ts);
console.log("Wrote src/lib/images.generated.ts");
